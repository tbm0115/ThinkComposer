        private static SyntheticDefinitionSelection SelectSyntheticDefinitions(DomainJsonDocument Document)
        {
            var Concepts = Document.ConceptDefinitions.Where(Item => Item != null && !String.IsNullOrWhiteSpace(Item.TechName)).ToList();
            var Relationships = Document.RelationshipDefinitions.Where(Item => Item != null && !String.IsNullOrWhiteSpace(Item.TechName)).ToList();
            if (Concepts.Count == 0 || Relationships.Count == 0)
                throw new InvalidDataException("The synthetic Composition seed Domain requires concept and relationship definitions.");

            var Relationship = Relationships.FirstOrDefault(Item => String.Equals(Item.TechName, "Relationship", StringComparison.OrdinalIgnoreCase))
                            ?? Relationships.FirstOrDefault(Item => Item.RoleDefinitions != null && Item.RoleDefinitions.Count >= 2)
                            ?? Relationships[0];
            var OriginRole = (Relationship.RoleDefinitions ?? new List<DomainJsonElement>())
                             .FirstOrDefault(Item => !String.Equals(Item.RoleType, "Target", StringComparison.OrdinalIgnoreCase));
            var TargetRole = (Relationship.RoleDefinitions ?? new List<DomainJsonElement>())
                             .FirstOrDefault(Item => String.Equals(Item.RoleType, "Target", StringComparison.OrdinalIgnoreCase));
            if (OriginRole == null || TargetRole == null)
                throw new InvalidDataException("The synthetic Composition relationship definition requires origin and target roles.");

            var Compatibility = (Document.RelationshipCompatibility ?? new List<DomainJsonRelationshipCompatibility>())
                                .FirstOrDefault(Item => String.Equals(Item.RelationshipDefinitionTechName,
                                                                      Relationship.TechName,
                                                                      StringComparison.OrdinalIgnoreCase));
            var DefaultConcept = Concepts.FirstOrDefault(Item => String.Equals(Item.TechName, "Concept", StringComparison.OrdinalIgnoreCase))
                              ?? Concepts[0];
            var OriginConcept = FindCompatibleConcept(Concepts, OriginRole.AssociableIdeaDefinitionTechNames,
                Compatibility == null ? null : Compatibility.AllowedOriginConceptDefinitionTechNames) ?? DefaultConcept;
            var TargetConcept = FindCompatibleConcept(Concepts, TargetRole.AssociableIdeaDefinitionTechNames,
                Compatibility == null ? null : Compatibility.AllowedTargetConceptDefinitionTechNames) ?? DefaultConcept;

            return new SyntheticDefinitionSelection
            {
                OriginConcept = OriginConcept,
                TargetConcept = TargetConcept,
                Relationship = Relationship,
                OriginRole = OriginRole,
                TargetRole = TargetRole
            };
        }

        private static DomainJsonElement FindCompatibleConcept(IEnumerable<DomainJsonElement> Concepts,
                                                               IEnumerable<string> RoleCandidates,
                                                               IEnumerable<string> CompatibilityCandidates)
        {
            var Requested = (RoleCandidates ?? Enumerable.Empty<string>())
                            .Concat(CompatibilityCandidates ?? Enumerable.Empty<string>())
                            .Where(Item => !String.IsNullOrWhiteSpace(Item))
                            .ToList();
            return Concepts.FirstOrDefault(Concept => Requested.Any(Item =>
                String.Equals(Item, Concept.TechName, StringComparison.OrdinalIgnoreCase)));
        }

