        private static CompositionJsonDomain BuildCompositionDomainContext(DomainJsonDocument DomainDocument,
                                                                            SyntheticDefinitionSelection Definitions)
        {
            var Source = DomainDocument.Domain;
            var Result = new CompositionJsonDomain
            {
                Id = Source.Id,
                Name = Source.Name,
                TechName = Source.TechName,
                Summary = Source.Summary,
                Description = Source.Description,
                TechSpec = Source.TechSpec,
                CompatibilitySignature = Source.CompatibilitySignature
            };

            foreach (var Definition in new[] { Definitions.OriginConcept, Definitions.TargetConcept }
                     .Where(Item => Item != null)
                     .GroupBy(Item => Item.TechName, StringComparer.OrdinalIgnoreCase)
                     .Select(Group => Group.First()))
                Result.Definitions.Add(ToCompositionDefinition(Definition, "ConceptDefinition"));
            Result.Definitions.Add(ToCompositionDefinition(Definitions.Relationship, "RelationshipDefinition"));
            return Result;
        }

