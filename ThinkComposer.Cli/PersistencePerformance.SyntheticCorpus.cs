        private static void CreateSyntheticComposition(string BaseCompositionPackage,
                                                       string BaseDomainPackage,
                                                       string OutputPackage)
        {
            var CompositionPayload = JsonPackagePersistence.ReadCompositionPackage(BaseCompositionPackage);
            var DomainPayload = JsonPackagePersistence.ReadDomainPackage(BaseDomainPackage);
            if (CompositionPayload.CompositionDocument == null)
                throw new InvalidDataException("The synthetic Composition seed has no /Composition.json payload.");
            if (DomainPayload.DomainDocument == null || DomainPayload.DomainDocument.Domain == null)
                throw new InvalidDataException("The synthetic Composition Domain seed has no /Domain.json payload.");

            var Document = CompositionPayload.CompositionDocument;
            var DomainDocument = DomainPayload.DomainDocument;
            var Definitions = SelectSyntheticDefinitions(DomainDocument);

            DomainDocument.ExportedAtUtc = SyntheticTimestamp;
            Document.ExportedAtUtc = SyntheticTimestamp;
            Document.TargetContext = null;
            Document.Requires = null;
            Document.ImportOptions = null;
            Document.VisualStrategy = null;
            Document.Operations = new List<CompositionJsonOperation>();
            Document.Groups = new List<CompositionJsonGroup>();
            Document.Warnings = new List<string>();

            var CompositionId = StableGuid("synthetic-composition");
            var RootViewId = StableGuid("synthetic-composition-view-0000");
            Document.Composition = new CompositionJsonComposition
            {
                Id = CompositionId,
                Name = "Synthetic JSON Persistence Composition",
                TechName = "Synthetic_JSON_Persistence_Composition",
                Summary = "Deterministic large Composition used by the JSON persistence benchmark.",
                Description = "Generated by ThinkComposer.Cli. Do not edit or commit generated corpus artifacts.",
                TechSpec = "5000 concepts; 7500 relationships; 5 views; 15000 visual representations; 15000 connector records.",
                ViewsPrefix = "View",
                RootViewId = RootViewId,
                ActiveViewId = RootViewId,
                Version = new CompositionJsonVersion
                {
                    VersionSequence = 1,
                    VersionNumber = "1.0.00",
                    Annotation = "Deterministic performance corpus",
                    Creator = "ThinkComposer.Cli",
                    LastModifier = "ThinkComposer.Cli",
                    Creation = SyntheticTimestamp,
                    LastModification = SyntheticTimestamp
                },
                Domain = BuildCompositionDomainContext(DomainDocument, Definitions)
            };

            Document.Ideas = BuildSyntheticConcepts(CompositionId, Definitions);
            Document.Relationships = new List<CompositionJsonRelationship>(SyntheticRelationshipCount);
            Document.Views = new List<CompositionJsonView>(SyntheticViewCount);

            for (var ViewIndex = 0; ViewIndex < SyntheticViewCount; ViewIndex++)
                BuildSyntheticView(Document, ViewIndex, CompositionId, Definitions);

            AssertSyntheticCompositionCounts(Document);

            var CompositionJson = CompositionJsonSerializer.Serialize(Document);
            var DomainJson = DomainJsonSerializer.Serialize(DomainDocument);
            WriteSyntheticPackage(OutputPackage, "composition",
                Document.Composition.Id, Document.Composition.Name, Document.Composition.TechName,
                new SyntheticJsonPart("composition", JsonPackagePersistence.CompositionJsonPartUri,
                                      CompositionJsonDocument.CurrentFormat, CompositionJson),
                new SyntheticJsonPart("embeddedDomain", JsonPackagePersistence.DomainJsonPartUri,
                                      DomainJsonDocument.CurrentFormat, DomainJson));
        }

        private static void CreateSyntheticDomain(string BaseDomainPackage, string OutputPackage)
        {
            var Payload = JsonPackagePersistence.ReadDomainPackage(BaseDomainPackage);
            var Document = Payload.DomainDocument;
            if (Document == null || Document.Domain == null)
                throw new InvalidDataException("The synthetic Domain seed has no /Domain.json payload.");

            Document.ExportedAtUtc = SyntheticTimestamp;
            Document.Domain.Id = StableGuid("synthetic-domain");
            Document.Domain.Name = "Synthetic JSON Persistence Domain";
            Document.Domain.TechName = "Synthetic_JSON_Persistence_Domain";
            Document.Domain.Summary = "Deterministic large Domain used by the JSON persistence benchmark.";
            Document.Domain.Description = "Generated by ThinkComposer.Cli. Do not edit or commit generated corpus artifacts.";
            Document.Domain.TechSpec = "500 concept definitions; 250 relationship definitions; 125 eight-field tables; 250 markers; 4 languages; 100 templates.";
            Document.Domain.CompatibilitySignature = null;
            Document.Operations = new List<DomainJsonOperation>();
            Document.Warnings = new List<string>();

            // Retain only the seed's field data-type identity. The benchmark contract specifies
            // exact final population sizes, so none of the measured collections may retain seed
            // entities in addition to the deterministic synthetic entities below.
            var DataTypeTechName = FindSeedFieldDataType(Document);
            Document.ConceptDefinitions = new List<DomainJsonElement>();
            Document.RelationshipDefinitions = new List<DomainJsonElement>();
            Document.TableDefinitions = new List<DomainJsonElement>();
            Document.MarkerDefinitions = new List<DomainJsonElement>();
            Document.ExternalLanguages = new List<DomainJsonElement>();
            Document.ConceptDefinitionOutputTemplates = new List<DomainJsonElement>();
            Document.RelationshipDefinitionOutputTemplates = new List<DomainJsonElement>();
            Document.RelationshipCompatibility = new List<DomainJsonRelationshipCompatibility>();

            for (var Index = 0; Index < SyntheticDomainConceptDefinitionCount; Index++)
                Document.ConceptDefinitions.Add(CreateSyntheticConceptDefinition(Index));

            for (var Index = 0; Index < SyntheticDomainRelationshipDefinitionCount; Index++)
                Document.RelationshipDefinitions.Add(CreateSyntheticRelationshipDefinition(Index));

            for (var Index = 0; Index < SyntheticDomainTableCount; Index++)
                Document.TableDefinitions.Add(CreateSyntheticTableDefinition(Index, DataTypeTechName));

            for (var Index = 0; Index < SyntheticDomainMarkerCount; Index++)
                Document.MarkerDefinitions.Add(CreateSyntheticMarkerDefinition(Index));

            for (var Index = 0; Index < SyntheticDomainLanguageCount; Index++)
                Document.ExternalLanguages.Add(CreateSyntheticLanguage(Index));

            for (var Index = 0; Index < SyntheticDomainTemplateCount; Index++)
                Document.ConceptDefinitionOutputTemplates.Add(CreateSyntheticTemplate(Index));

            AssertSyntheticDomainCounts(Document);

            var DomainJson = DomainJsonSerializer.Serialize(Document);
            WriteSyntheticPackage(OutputPackage, "domain",
                Document.Domain.Id, Document.Domain.Name, Document.Domain.TechName,
                new SyntheticJsonPart("domain", JsonPackagePersistence.DomainJsonPartUri,
                                      DomainJsonDocument.CurrentFormat, DomainJson));
        }

        private static List<CompositionJsonIdea> BuildSyntheticConcepts(string CompositionId,
                                                                        SyntheticDefinitionSelection Definitions)
        {
            var Result = new List<CompositionJsonIdea>(SyntheticConceptCount);
            for (var Index = 0; Index < SyntheticConceptCount; Index++)
            {
                var Definition = Index < SyntheticConceptCount / 2
                               ? Definitions.OriginConcept
                               : Definitions.TargetConcept;
                Result.Add(new CompositionJsonIdea
                {
                    Id = SyntheticConceptId(Index),
                    Kind = "Concept",
                    Name = "Synthetic Concept " + Index.ToString("D4", CultureInfo.InvariantCulture),
                    TechName = SyntheticConceptTechName(Index),
                    Summary = "Deterministic concept " + Index.ToString(CultureInfo.InvariantCulture),
                    DefinitionId = Definition.Id,
                    DefinitionTechName = Definition.TechName,
                    DefinitionName = Definition.Name,
                    ContainerId = CompositionId,
                    ContainerTechName = "Synthetic_JSON_Persistence_Composition"
                });
            }
            return Result;
        }

        private static void BuildSyntheticView(CompositionJsonDocument Document, int ViewIndex,
                                               string CompositionId,
                                               SyntheticDefinitionSelection Definitions)
        {
            const int ConceptsPerRolePerView = 750;
            const int RelationshipsPerView = 1500;
            const int ConceptRolePopulation = SyntheticConceptCount / 2;

            var ViewId = StableGuid("synthetic-composition-view-" + ViewIndex.ToString("D4", CultureInfo.InvariantCulture));
            var View = new CompositionJsonView
            {
                Id = ViewId,
                Name = "Synthetic View " + ViewIndex.ToString("D2", CultureInfo.InvariantCulture),
                TechName = "Synthetic_View_" + ViewIndex.ToString("D2", CultureInfo.InvariantCulture),
                Summary = "Three thousand deterministic visual representations.",
                OwnerIdeaId = CompositionId,
                OwnerIdeaTechName = "Synthetic_JSON_Persistence_Composition"
            };

            var OriginIndexes = new int[ConceptsPerRolePerView];
            var TargetIndexes = new int[ConceptsPerRolePerView];
            var ConceptRepresentationIds = new Dictionary<int, string>();
            for (var Local = 0; Local < ConceptsPerRolePerView; Local++)
            {
                OriginIndexes[Local] = (ViewIndex * 500 + Local) % ConceptRolePopulation;
                TargetIndexes[Local] = ConceptRolePopulation + ((ViewIndex * 500 + Local) % ConceptRolePopulation);

                AddConceptVisual(View, ViewIndex, OriginIndexes[Local], Local, false, ConceptRepresentationIds);
                AddConceptVisual(View, ViewIndex, TargetIndexes[Local], Local, true, ConceptRepresentationIds);
            }

            for (var Local = 0; Local < RelationshipsPerView; Local++)
            {
                var RelationshipIndex = ViewIndex * RelationshipsPerView + Local;
                var OriginIndex = OriginIndexes[Local % ConceptsPerRolePerView];
                var TargetIndex = TargetIndexes[Local % ConceptsPerRolePerView];
                var Relationship = CreateSyntheticRelationship(RelationshipIndex, CompositionId,
                                                               OriginIndex, TargetIndex, Definitions);
                Document.Relationships.Add(Relationship);
                View.Visuals.Add(CreateRelationshipVisual(ViewIndex, Local, RelationshipIndex,
                                                          OriginIndex, TargetIndex, Relationship,
                                                          ConceptRepresentationIds, Definitions));
            }

            Document.Views.Add(View);
        }

