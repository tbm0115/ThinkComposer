            return "Synthetic_Relationship_" + Index.ToString("D4", CultureInfo.InvariantCulture);
        }

        private static string SyntheticRelationshipLinkId(int Index, bool IsTarget)
        {
            return StableGuid("synthetic-relationship-link-" + Index.ToString("D4", CultureInfo.InvariantCulture) +
                              (IsTarget ? "-target" : "-origin"));
        }

        private static string StableGuid(string Seed)
        {
            using (var Hash = SHA256.Create())
            {
                var Digest = Hash.ComputeHash(Encoding.UTF8.GetBytes("ThinkComposer.JsonPersistenceCorpus/" + Seed));
                var Bytes = new byte[16];
                Array.Copy(Digest, Bytes, Bytes.Length);
                return new Guid(Bytes).ToString("D");
            }
        }

