        private static string FindSeedFieldDataType(DomainJsonDocument Document)
        {
            return (Document.TableDefinitions ?? new List<DomainJsonElement>())
                   .Where(Table => Table != null)
                   .SelectMany(Table => Table.Fields ?? new List<DomainJsonElement>())
                   .Where(Field => Field != null && !String.IsNullOrWhiteSpace(Field.DataTypeTechName))
                   .Select(Field => Field.DataTypeTechName)
                   .FirstOrDefault() ?? "Text";
        }

        private static void AssertSyntheticCompositionCounts(CompositionJsonDocument Document)
        {
            var Visuals = Document.Views.Sum(View => View.Visuals.Count);
            var Connectors = Document.Views.Sum(View => View.Visuals.Sum(Visual => Visual.Connectors.Count));
            if (Document.Ideas.Count != SyntheticConceptCount ||
                Document.Relationships.Count != SyntheticRelationshipCount ||
                Document.Views.Count != SyntheticViewCount ||
                Visuals != SyntheticVisualCount || Connectors != SyntheticConnectorCount)
                throw new InvalidDataException("Synthetic Composition count assertion failed: concepts=" + Document.Ideas.Count +
                    ", relationships=" + Document.Relationships.Count + ", views=" + Document.Views.Count +
                    ", visuals=" + Visuals + ", connectors=" + Connectors + ".");
        }

        private static void AssertSyntheticDomainCounts(DomainJsonDocument Document)
        {
            var TemplateCount = Document.ConceptDefinitionOutputTemplates.Count +
                                Document.RelationshipDefinitionOutputTemplates.Count;
            if (Document.ConceptDefinitions.Count != SyntheticDomainConceptDefinitionCount ||
                Document.RelationshipDefinitions.Count != SyntheticDomainRelationshipDefinitionCount ||
                Document.TableDefinitions.Count != SyntheticDomainTableCount ||
                Document.TableDefinitions.Any(Table => Table == null || Table.Fields == null ||
                                                        Table.Fields.Count != SyntheticDomainFieldsPerTable) ||
                Document.MarkerDefinitions.Count != SyntheticDomainMarkerCount ||
                Document.ExternalLanguages.Count != SyntheticDomainLanguageCount ||
                TemplateCount != SyntheticDomainTemplateCount)
                throw new InvalidDataException("Synthetic Domain count assertion failed: concept definitions=" +
                    Document.ConceptDefinitions.Count + ", relationship definitions=" +
                    Document.RelationshipDefinitions.Count + ", tables=" + Document.TableDefinitions.Count +
                    ", markers=" + Document.MarkerDefinitions.Count + ", languages=" +
                    Document.ExternalLanguages.Count + ", templates=" + TemplateCount + ".");
        }

        private static void AssertCanonicalSyntheticPackageCounts(string PackagePath, string PackageKind)
        {
            if (String.Equals(PackageKind, "composition", StringComparison.OrdinalIgnoreCase))
            {
                var Payload = JsonPackagePersistence.ReadCompositionPackage(PackagePath);
                if (Payload == null || Payload.CompositionDocument == null)
                    throw new InvalidDataException("Canonical synthetic Composition has no authoritative /Composition.json payload.");

                AssertSyntheticCompositionCounts(Payload.CompositionDocument);
                return;
            }

            if (String.Equals(PackageKind, "domain", StringComparison.OrdinalIgnoreCase))
            {
                var Payload = JsonPackagePersistence.ReadDomainPackage(PackagePath);
                if (Payload == null || Payload.DomainDocument == null)
                    throw new InvalidDataException("Canonical synthetic Domain has no authoritative /Domain.json payload.");

                AssertCanonicalSyntheticDomainCounts(Payload.DomainDocument);
                return;
            }

            throw new InvalidDataException("Unsupported canonical synthetic package kind '" +
                                           PackageKind.ToStringAlways("<none>") + "'.");
        }

        private static void AssertCanonicalSyntheticDomainCounts(DomainJsonDocument Document)
        {
            var ConceptDefinitions = SyntheticElements(Document.ConceptDefinitions,
                                                        "Synthetic_Concept_Definition_");
            var RelationshipDefinitions = SyntheticElements(Document.RelationshipDefinitions,
                                                             "Synthetic_Relationship_Definition_");
            var Tables = SyntheticElements(Document.TableDefinitions, "Synthetic_Table_");
            var Markers = SyntheticElements(Document.MarkerDefinitions, "Synthetic_Marker_");
            var Languages = SyntheticElements(Document.ExternalLanguages, "Synthetic_Language_");
            var Templates = (Document.ConceptDefinitionOutputTemplates ?? new List<DomainJsonElement>())
                           .Concat(Document.RelationshipDefinitionOutputTemplates ?? new List<DomainJsonElement>())
                           .Where(IsCanonicalSyntheticTemplate)
                           .ToList();
            var InvalidTableFieldCounts = Tables.Count(Table => Table.Fields == null ||
                                                                 Table.Fields.Count != SyntheticDomainFieldsPerTable);
            var SyntheticFieldCount = Tables.Sum(Table => Table.Fields == null ? 0 : Table.Fields.Count);

            // Native Domain construction can retain system-owned defaults.  Count only the
            // deterministic Synthetic_* population so those defaults neither hide a loss nor
            // make an otherwise faithful canonicalization fail.
            if (ConceptDefinitions.Count != SyntheticDomainConceptDefinitionCount ||
                RelationshipDefinitions.Count != SyntheticDomainRelationshipDefinitionCount ||
                Tables.Count != SyntheticDomainTableCount || InvalidTableFieldCounts != 0 ||
                Markers.Count != SyntheticDomainMarkerCount ||
                Languages.Count != SyntheticDomainLanguageCount ||
                Templates.Count != SyntheticDomainTemplateCount)
                throw new InvalidDataException(
                    "Canonical synthetic Domain count assertion failed: synthetic concept definitions=" +
                    ConceptDefinitions.Count.ToString(CultureInfo.InvariantCulture) +
                    ", relationship definitions=" + RelationshipDefinitions.Count.ToString(CultureInfo.InvariantCulture) +
                    ", tables=" + Tables.Count.ToString(CultureInfo.InvariantCulture) +
                    ", fields=" + SyntheticFieldCount.ToString(CultureInfo.InvariantCulture) +
                    ", tables with non-eight field counts=" + InvalidTableFieldCounts.ToString(CultureInfo.InvariantCulture) +
                    ", markers=" + Markers.Count.ToString(CultureInfo.InvariantCulture) +
                    ", languages=" + Languages.Count.ToString(CultureInfo.InvariantCulture) +
                    ", templates=" + Templates.Count.ToString(CultureInfo.InvariantCulture) + ".");
        }

        private static bool IsCanonicalSyntheticTemplate(DomainJsonElement Item)
        {
            return Item != null &&
                   String.Equals(Item.OwnerScope, "conceptDefinition", StringComparison.OrdinalIgnoreCase) &&
                   !String.IsNullOrEmpty(Item.OwnerTechName) &&
                   Item.OwnerTechName.StartsWith("Synthetic_Concept_Definition_", StringComparison.Ordinal) &&
                   String.Equals(Item.ExternalLanguageTechName, "Synthetic_Language_00", StringComparison.Ordinal) &&
                   !String.IsNullOrEmpty(Item.TemplateText) &&
                   Item.TemplateText.StartsWith("%%:TemplateRole=Fragment\nSynthetic template ", StringComparison.Ordinal) &&
                   Item.ExtendsBaseTemplate == false;
        }

        private static List<DomainJsonElement> SyntheticElements(IEnumerable<DomainJsonElement> Source,
                                                                 string TechNamePrefix)
        {
            return (Source ?? Enumerable.Empty<DomainJsonElement>())
                   .Where(Item => Item != null &&
                                  !String.IsNullOrEmpty(Item.TechName) &&
                                  Item.TechName.StartsWith(TechNamePrefix, StringComparison.Ordinal))
                   .ToList();
        }

        private static void WriteSyntheticPackage(string OutputPackage, string PackageKind,
                                                  string SourceId, string SourceName, string SourceTechName,
                                                  params SyntheticJsonPart[] Parts)
        {
            if (Parts == null || Parts.Length == 0)
                throw new ArgumentException("A synthetic package requires at least one authoritative JSON part.", "Parts");

            OutputPackage = Path.GetFullPath(OutputPackage);
            EnsureParent(OutputPackage);
            using (var Package = System.IO.Packaging.Package.Open(OutputPackage, FileMode.Create, FileAccess.ReadWrite))
            {
                foreach (var Part in Parts)
                    WriteSyntheticPart(Package, Part.PartUri, Part.Bytes);

                var Manifest = BuildSyntheticManifest(PackageKind, SourceId, SourceName, SourceTechName, Parts);
                WriteSyntheticPart(Package, JsonPackagePersistence.ManifestPartUri,
                                   Utf8NoBom.GetBytes(Json.Serialize(Manifest)));
                Package.Flush();
            }
        }

        private static SortedDictionary<string, object> BuildSyntheticManifest(string PackageKind,
                                                                               string SourceId,
                                                                               string SourceName,
                                                                               string SourceTechName,
                                                                               IEnumerable<SyntheticJsonPart> Parts)
        {
            var AuthoritativeParts = Parts.Select(Part => (object)new SortedDictionary<string, object>(StringComparer.Ordinal)
            {
                { "bytes", Part.Bytes.LongLength },
                { "format", Part.Format },
                { "kind", Part.Kind },
                { "partUri", Part.PartUri.ToString() },
                { "sha256", HashBytes(Part.Bytes) }
            }).ToList();

            return new SortedDictionary<string, object>(StringComparer.Ordinal)
            {
                { "application", "ThinkComposer" },
                { "applicationVersion", "performance-corpus-1" },
                { "authoritativeParts", AuthoritativeParts },
                { "format", "ThinkComposer.Package" },
                { "formatVersion", 1 },
                { "legacyBinaryFallback", new SortedDictionary<string, object>(StringComparer.Ordinal) { { "present", false } } },
                { "packageKind", PackageKind },
                { "persistenceFormat", "json" },
                { "persistenceFormatVersion", 1 },
                { "savedAtUtc", SyntheticTimestamp },
                { "sidecars", new SortedDictionary<string, object>(StringComparer.Ordinal) { { "interchangeManifestUri", "/Interchange/manifest.json" } } },
                { "source", new SortedDictionary<string, object>(StringComparer.Ordinal)
                    {
                        { "id", SourceId },
                        { "name", SourceName },
                        { "summary", "Deterministic JSON persistence performance corpus." },
                        { "techName", SourceTechName }
                    }
                },
                { "warnings", new List<string>() }
            };
        }

        private static void WriteSyntheticPart(Package Package, Uri PartUri, byte[] Bytes)
        {
            if (Package.PartExists(PartUri))
                Package.DeletePart(PartUri);
            var Part = Package.CreatePart(PartUri, JsonContentType, CompressionOption.Maximum);
            using (var Stream = Part.GetStream(FileMode.Create, FileAccess.Write))
                Stream.Write(Bytes, 0, Bytes.Length);
        }

        private static string SyntheticConceptId(int Index)
        {
            return StableGuid("synthetic-concept-" + Index.ToString("D4", CultureInfo.InvariantCulture));
        }

        private static string SyntheticConceptTechName(int Index)
        {
            return "Synthetic_Concept_" + Index.ToString("D4", CultureInfo.InvariantCulture);
        }

        private static string SyntheticRelationshipId(int Index)
